"""Regenerate docs/api.md and docs/data-model.md from the code (run after API or model changes).

    uv run python scripts/gen_docs.py
"""

import os
import sys
from collections import defaultdict
from pathlib import Path

os.environ.setdefault("LMS_ENVIRONMENT", "test")
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.core.database import Base  # noqa: E402
from app.main import create_app  # noqa: E402

DOCS = Path(__file__).resolve().parents[2] / "docs"


def api_doc() -> str:
    spec = create_app().openapi()
    groups: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for path, methods in spec["paths"].items():
        for method, op in methods.items():
            tag = (op.get("tags") or ["other"])[0]
            groups[tag].append((method.upper(), path, op.get("summary", "")))
    lines = ["# API map", "", "Generated by `backend/scripts/gen_docs.py` from the OpenAPI schema. "
             "Interactive docs: `/api/docs`.", "", f"{sum(map(len, groups.values()))} operations.", ""]
    for tag in sorted(groups):
        lines += [f"## {tag}", "", "| Method | Path | Summary |", "|---|---|---|"]
        lines += [f"| {m} | `{p}` | {s} |" for m, p, s in sorted(groups[tag], key=lambda r: (r[1], r[0]))]
        lines.append("")
    return "\n".join(lines)


def model_doc() -> str:
    lines = ["# Data model", "", "Generated by `backend/scripts/gen_docs.py` from the SQLAlchemy models.", ""]
    for table in sorted(Base.metadata.sorted_tables, key=lambda t: t.name):
        lines += [f"## `{table.name}`", "", "| Column | Type | Null | Notes |", "|---|---|---|---|"]
        for col in table.columns:
            notes = []
            if col.primary_key:
                notes.append("PK")
            notes += [f"→ `{fk.target_fullname}`" for fk in col.foreign_keys]
            if col.unique:
                notes.append("unique")
            if col.index:
                notes.append("indexed")
            lines.append(f"| {col.name} | {col.type} | {'yes' if col.nullable else 'no'} | {', '.join(notes)} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    (DOCS / "api.md").write_text(api_doc(), encoding="utf-8")
    (DOCS / "data-model.md").write_text(model_doc(), encoding="utf-8")
    print("Wrote docs/api.md and docs/data-model.md")
